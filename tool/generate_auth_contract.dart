import 'dart:convert';
import 'dart:io';

// Deliberately generates only this slice's DTO closure, from the frozen contract.
void main(List<String> args) {
  final specOption = args.where((arg) => arg.startsWith('--spec=')).firstOrNull;
  final positional = args.where((arg) => !arg.startsWith('--spec=')).toList();
  final output = positional.isEmpty
      ? "lib/src/auth_contract.g.dart"
      : positional.first;
  final roots = positional.length < 2
      ? ["Credentials", "LoginResponse", "Vehicle"]
      : positional.skip(1);
  final spec = jsonDecode(
    File(specOption?.substring(7) ?? 'docs/contracts/openapi-v1.json')
        .readAsStringSync(),
  ) as Map<String, dynamic>;
  final schemas = spec['components']['schemas'] as Map<String, dynamic>;
  final selected = <String>{};
  void visit(String name) {
    if (!selected.add(name)) return;
    void scan(dynamic node) {
      if (node is Map) {
        if (node[r'$ref'] case final String ref) visit(ref.split('/').last);
        node.values.forEach(scan);
      } else if (node is List) {
        node.forEach(scan);
      }
    }

    scan(schemas[name]);
  }

  for (final root in roots) {
    visit(root);
  }
  String camel(String s) =>
      s.replaceAllMapped(RegExp(r'_([a-z])'), (m) => m[1]!.toUpperCase());
  String schemaName(String name) => !name.contains('__')
      ? name
      : name
            .split(RegExp('_+'))
            .where((part) => part.isNotEmpty)
            .map((part) => part[0].toUpperCase() + part.substring(1))
            .join();
  String type(Map<String, dynamic> s) {
    if (s['anyOf'] case final List values) {
      return '${type(Map<String, dynamic>.from(values.firstWhere((v) => v['type'] != 'null')))}?';
    }
    if (s[r'$ref'] case final String ref) {
      return schemaName(ref.split('/').last);
    }
    return switch (s['type']) {
      'integer' => 'int',
      'number' => 'num',
      'boolean' => 'bool',
      'array' => 'List<${type(Map<String, dynamic>.from(s['items']))}>',
      'object' when s['additionalProperties'] is Map =>
        'Map<String, ${type(Map<String, dynamic>.from(s['additionalProperties']))}>',
      'string' => s['format'] == 'date-time' ? 'DateTime' : 'String',
      _ => throw StateError('Unsupported $s'),
    };
  }

  String decodeValue(String input, Map<String, dynamic> s) {
    if (s['anyOf'] case final List values) {
      return '$input == null ? null : ${decodeValue(input, Map<String, dynamic>.from(values.firstWhere((v) => v['type'] != 'null')))}';
    }
    if (s[r'$ref'] case final String ref) {
      return '${schemaName(ref.split('/').last)}.fromJson(object($input))';
    }
    if (s['type'] == 'array') {
      return "field<List<dynamic>>($input).map((item) => ${decodeValue('item', Map<String, dynamic>.from(s['items']))}).toList()";
    }
    if (s['type'] == 'object' && s['additionalProperties'] is Map) {
      return "object($input).map((key, value) => MapEntry(key, ${decodeValue('value', Map<String, dynamic>.from(s['additionalProperties']))}))";
    }
    if (s['format'] == 'date-time') return 'instant($input)';
    return "field<${type(s)}>($input)";
  }

  String decode(String name, Map<String, dynamic> s) {
    final input = s.containsKey('default')
        ? "(json.containsKey('$name') ? json['$name'] : ${jsonEncode(s['default'])})"
        : "json['$name']";
    return decodeValue(input, s);
  }

  final out = StringBuffer('''// GENERATED by tool/generate_auth_contract.dart from frozen OpenAPI. Do not edit.
Map<String,dynamic> object(dynamic value) {
  if (value is! Map<String,dynamic>) { throw const FormatException('Expected object'); }
  return value;
}
T field<T>(dynamic value) {
  if (value is! T) { throw const FormatException('Unexpected field type'); }
  return value;
}
DateTime instant(dynamic value) {
  final text = field<String>(value);
  if (!RegExp(r'(Z|[+-]\\d{2}:\\d{2})\$').hasMatch(text)) { throw const FormatException('Timezone required'); }
  return DateTime.parse(text).toUtc();
}
''');
  for (final name in selected) {
    final className = schemaName(name);
    final schema = schemas[name] as Map<String, dynamic>;
    final props = schema['properties'] as Map<String, dynamic>;
    final requiredFields = (schema['required'] as List? ?? []).cast<String>();
    bool optional(String key, Map<String, dynamic> value) =>
        !requiredFields.contains(key) &&
        !value.containsKey('default') &&
        !type(value).endsWith('?');
    out.writeln('class $className {');
    out.writeln(
      props.isEmpty
          ? '$className();'
          : '$className({${props.keys.map((k) => 'required this.${camel(k)}').join(',')}});',
    );
    for (final e in props.entries) {
      out.writeln(
        'final ${type(e.value)}${optional(e.key, e.value) ? '?' : ''} ${camel(e.key)};',
      );
    }
    out.writeln('factory $className.fromJson(Map<String,dynamic> json) {');
    for (final k in schema['required'] as List? ?? []) {
      out.writeln(
        "if (!json.containsKey('$k')) { throw const FormatException('Missing required field: $k'); }",
      );
    }
    out.writeln(
      'return $className(${props.entries.map((e) => '${camel(e.key)}: ${optional(e.key, e.value) ? "json['${e.key}'] == null ? null : " : ''}${decode(e.key, e.value)}').join(',')});}',
    );
    if (name == 'Credentials') {
      out.writeln("Map<String,dynamic> toJson()=>{'password':password};");
    }
    out.writeln('}');
  }
  // The 0.2 charging event has a property named `field`; avoid shadowing the
  // decoding helper inside its factory without changing the legacy outputs.
  final source = specOption == null
      ? out.toString()
      : out.toString().replaceAll(RegExp(r'\bfield<'), 'decodeField<');
  File(output).writeAsStringSync(source);
  final formatted = Process.runSync(Platform.resolvedExecutable, [
    'format',
    output,
  ]);
  if (formatted.exitCode != 0) {
    throw StateError('Generated DTO formatting failed');
  }
}
