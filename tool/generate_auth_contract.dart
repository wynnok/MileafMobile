import 'dart:convert';
import 'dart:io';

// Deliberately generates only this slice's DTO closure, from the frozen contract.
void main() {
  final spec = jsonDecode(
    File('docs/contracts/openapi-v1.json').readAsStringSync(),
  ) as Map<String, dynamic>;
  final schemas = spec['components']['schemas'] as Map<String, dynamic>;
  final selected = <String>{};
  void visit(String name) {
    if (!selected.add(name)) return;
    void scan(dynamic node) {
      if (node is Map) {
        if (node[r'$ref'] case final String ref) visit(ref.split('/').last);
        node.values.forEach(scan);
      } else if (node is List) {
        node.forEach(scan);
      }
    }

    scan(schemas[name]);
  }

  for (final root in ['Credentials', 'LoginResponse', 'Vehicle']) {
    visit(root);
  }
  String camel(String s) =>
      s.replaceAllMapped(RegExp(r'_([a-z])'), (m) => m[1]!.toUpperCase());
  String type(Map<String, dynamic> s) {
    if (s['anyOf'] case final List values) {
      return '${type(Map<String, dynamic>.from(values.firstWhere((v) => v['type'] != 'null')))}?';
    }
    if (s[r'$ref'] case final String ref) return ref.split('/').last;
    return switch (s['type']) {
      'integer' => 'int',
      'number' => 'num',
      'string' => s['format'] == 'date-time' ? 'DateTime' : 'String',
      _ => throw StateError('Unsupported $s'),
    };
  }

  String decode(String name, Map<String, dynamic> s) {
    final input = "json['$name']";
    if (s['anyOf'] case final List values) {
      return '$input == null ? null : ${decode(name, Map<String, dynamic>.from(values.firstWhere((v) => v['type'] != 'null')))}';
    }
    if (s[r'$ref'] case final String ref) {
      return '${ref.split('/').last}.fromJson(object($input))';
    }
    if (s['format'] == 'date-time') return 'instant($input)';
    return "field<${type(s)}>($input)";
  }

  final out = StringBuffer('''// GENERATED by tool/generate_auth_contract.dart from frozen OpenAPI. Do not edit.
Map<String,dynamic> object(dynamic value) {
  if (value is! Map<String,dynamic>) { throw const FormatException('Expected object'); }
  return value;
}
T field<T>(dynamic value) {
  if (value is! T) { throw const FormatException('Unexpected field type'); }
  return value;
}
DateTime instant(dynamic value) {
  final text = field<String>(value);
  if (!RegExp(r'(Z|[+-]\\d{2}:\\d{2})\$').hasMatch(text)) { throw const FormatException('Timezone required'); }
  return DateTime.parse(text).toUtc();
}
''');
  for (final name in selected) {
    final schema = schemas[name] as Map<String, dynamic>;
    final props = schema['properties'] as Map<String, dynamic>;
    out.writeln('class $name {');
    out.writeln(
      '$name({${props.keys.map((k) => 'required this.${camel(k)}').join(',')}});',
    );
    for (final e in props.entries) {
      out.writeln('final ${type(e.value)} ${camel(e.key)};');
    }
    out.writeln('factory $name.fromJson(Map<String,dynamic> json) {');
    for (final k in schema['required'] as List? ?? []) {
      out.writeln(
        "if (!json.containsKey('$k')) { throw const FormatException('Missing required field: $k'); }",
      );
    }
    out.writeln(
      'return $name(${props.entries.map((e) => '${camel(e.key)}: ${decode(e.key, e.value)}').join(',')});}',
    );
    if (name == 'Credentials') {
      out.writeln("Map<String,dynamic> toJson()=>{'password':password};");
    }
    out.writeln('}');
  }
  File('lib/src/auth_contract.g.dart').writeAsStringSync(out.toString());
  final formatted = Process.runSync(Platform.resolvedExecutable, [
    'format',
    'lib/src/auth_contract.g.dart',
  ]);
  if (formatted.exitCode != 0) {
    throw StateError('Generated DTO formatting failed');
  }
}
